FSI, PDI = "⁨", "⁩"  # Unicode direction isolates


def t(lang: str, key: str, _iso: bool = True, **kw) -> str:
    """Translate. Inserted text values are wrapped in direction isolates so an Arabic topic
    name inside an English sentence (or the reverse) keeps its own reading order.
    Pass _iso=False when the result is data sent to the backend, not display text."""
    pair = S.get(key)
    if pair is None:
        return key
    text = pair[1] if lang == "en" else pair[0]
    if not kw:
        return text
    if _iso:
        kw = {k: f"{FSI}{v}{PDI}" if isinstance(v, str) else v for k, v in kw.items()}
    return text.format(**kw)


def strip_isolates(text: str) -> str:
    return text.replace(FSI, "").replace(PDI, "")


def direction(lang: str) -> str:
    return "ltr" if lang == "en" else "rtl"
